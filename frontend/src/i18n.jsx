const LanguageContext = createContext(null)

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => (
    localStorage.getItem('cs_language') === 'hi' ? 'hi' : 'en'
  ))

  const setLanguage = nextLanguage => {
    const next = nextLanguage === 'hi' ? 'hi' : 'en'
    localStorage.setItem('cs_language', next)
    setLanguageState(next)
  }

  useEffect(() => {
    document.documentElement.lang = language === 'hi' ? 'hi' : 'en'
  }, [language])

  const value = useMemo(() => ({ language, setLanguage }), [language])
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider')
  return context
}

function translateNode(node, language) {
  if (typeof node === 'string') return translateText(node, language)
  if (Array.isArray(node)) return Children.map(node, child => translateNode(child, language))
  if (!isValidElement(node)) return node

  const props = {}
  for (const [name, value] of Object.entries(node.props)) {
    if (name === 'children') {
      props.children = translateNode(value, language)
    } else if (['aria-label', 'placeholder', 'title', 'alt'].includes(name) && typeof value === 'string') {
      props[name] = translateText(value, language)
    }
  }
  return cloneElement(node, props)
}

export function LocalizedContent({ children }) {
  const { language } = useLanguage()
  return translateNode(children, language)
}
